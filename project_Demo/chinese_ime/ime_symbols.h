static int imeSymbolCount(int category, int english)
{
	if (category < 0 || category >= SYMBOL_CATEGORY_COUNT)
		return 0;
	const char* const* table = category == 0 && english ? s_english_symbols : s_symbol_grid[category];
	int count = 0;
	while (count < SYMBOL_CATEGORY_CAP && table[count])
		++count;
	return count;
}
static const char* imeSymbolAt(int category, int index, int english)
{
	if (index < 0 || index >= imeSymbolCount(category, english))
		return NULL;
	return (category == 0 && english ? s_english_symbols : s_symbol_grid[category])[index];
}
