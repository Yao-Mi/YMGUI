#!/usr/bin/env python3
"""Generate self-contained 4-bpp proportional UI glyphs from DejaVu Sans.

The font comes from the system's DejaVu Sans installation. The generated glyph
data is committed so building this example needs neither Pillow nor a TTF file.
DejaVu's font license is documented in assets/FONT_LICENSE.txt.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"


def font_data(name, size, cell_w, cell_h, baseline):
    font = ImageFont.truetype(FONT, size)
    bpr = (cell_w + 1) // 2
    bitmap = []
    advances = []
    for code in range(32, 127):
        ch = chr(code)
        img = Image.new("L", (cell_w, cell_h), 0)
        # All glyphs share a baseline, including capitals and descenders.
        ImageDraw.Draw(img).text((1, baseline), ch, fill=255, font=font, anchor="ls")
        advances.append(min(cell_w, max(3, round(font.getlength(ch)))))
        px = img.load()
        for row in range(cell_h):
            for pair in range(bpr):
                left = px[pair * 2, row] >> 4
                right = px[pair * 2 + 1, row] >> 4 if pair * 2 + 1 < cell_w else 0
                bitmap.append((left << 4) | right)
    lines = [f"static const uint8 {name}_bitmap[] = {{"]
    for off in range(0, len(bitmap), 24):
        lines.append("    " + ", ".join(f"0x{v:02X}" for v in bitmap[off:off + 24]) + ",")
    lines += ["};", f"const uint8 {name}_advance[95] = {{"]
    for off in range(0, 95, 24):
        lines.append("    " + ", ".join(str(v) for v in advances[off:off + 24]) + ",")
    lines += ["};", f"const GYfont {name} = {{",
              f"    {name}_bitmap, NULL, 0, 32, 126, {cell_w}, {cell_h}, {bpr}, 4, NULL, NULL",
              "};", ""]
    return lines


output = ["// Generated by gen_font.py from DejaVu Sans. Do not edit manually.",
          '#include "phone_font.h"', ""]
output += font_data("phone_font_regular", 14, 20, 24, 17)
output += font_data("phone_font_display", 52, 64, 66, 52)
output += font_data("phone_font_small", 11, 16, 18, 13)
output += font_data("phone_font_title", 26, 34, 36, 27)
(ROOT / "phone_font.c").write_text("\n".join(output))
